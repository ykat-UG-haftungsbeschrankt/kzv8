#[inline(never)]
pub(crate) fn align_up(value: usize, alignment: usize) -> Option<usize> {
    if alignment == 0 || !alignment.is_power_of_two() {
        return None;
    }
    let adjustment = alignment - 1;
    value
        .checked_add(adjustment)
        .map(|aligned| aligned & !adjustment)
}